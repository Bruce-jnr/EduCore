import { Router } from 'express';
import bcrypt from 'bcryptjs';
import { OAuth2Client } from 'google-auth-library';
import { prisma } from '../../config/prisma.js';
import { env } from '../../config/env.js';
import { asyncHandler } from '../../utils/async-handler.js';
import { validate } from '../../middleware/validate.js';
import { googleRequestOrigin, createGoogleRateLimit } from '../auth/google-security.js';
import { createGoogleIdentity } from '../auth/google-identity.js';
import { listLessonSchema, getLessonSchema } from '../lesson-plans/lesson-plan.validation.js';
import { teacherSignupSchema, teacherLoginSchema, teacherGoogleSchema, teacherChallengeSchema, personalCreateSchema, personalUpdateSchema } from './teacher.validation.js';
import { createTeacherAuthService, teacherProfile } from './teacher-auth.service.js';
import { createTeacherSessions, createTeacherAuthenticate } from './teacher-session.js';
import { createPersonalLessonService } from './personal-lesson.service.js';

import {paystackService,paystackClient} from '../payments/paystack.runtime.js';
import {lessonCheckoutSchema,paymentVerifySchema} from '../payments/paystack.routes.js';
import { createLessonBilling } from './lesson-billing.service.js';
import { lessonQuoteSchema,lessonPurchaseSchema } from './lesson-billing.validation.js';
const billing=createLessonBilling(prisma);
export const teacherRouter = Router();
const google = new OAuth2Client();
const sessions = createTeacherSessions(env.JWT_SECRET,env.JWT_EXPIRES_IN);
const identity = createGoogleIdentity({ clientId: env.GOOGLE_CLIENT_ID, secret: env.JWT_SECRET, fallbackName: 'Teacher Account', verifyIdToken: options => google.verifyIdToken(options) });
const auth = createTeacherAuthService({ db: prisma, hash: bcrypt.hash, compare: bcrypt.compare, signSession: sessions.sign, identity });
const authenticateTeacher = createTeacherAuthenticate(prisma,sessions);
const lessons = createPersonalLessonService(prisma);
const respond = (fn,status=200) => asyncHandler(async(req,res)=>res.set('Cache-Control','no-store').status(status).json({success:true,data:await fn(req)}));
const publicAuth = Router();
publicAuth.get('/google/config',respond(()=>({clientId:env.GOOGLE_CLIENT_ID,signupEnabled:Boolean(env.GOOGLE_CLIENT_ID)})));
publicAuth.get('/me',authenticateTeacher,respond(req=>teacherProfile(req.teacher)));
publicAuth.use(googleRequestOrigin(env.CLIENT_URL),createGoogleRateLimit());
publicAuth.post('/signup',validate(teacherSignupSchema),respond(req=>auth.register(req.validated.body),201));
publicAuth.post('/login',validate(teacherLoginSchema),respond(req=>auth.login(req.validated.body)));
publicAuth.post('/google/challenge',validate(teacherChallengeSchema),respond(req=>({challenge:identity.challenge(`teacher-${req.validated.body.intent}`)})));
for(const intent of ['signin','signup']) publicAuth.post(`/google/${intent}`,validate(teacherGoogleSchema),respond(req=>auth.google(intent,req.validated.body),intent==='signup'?201:200));
teacherRouter.use('/auth',publicAuth);
teacherRouter.use('/billing',authenticateTeacher);
teacherRouter.post('/billing/paystack/initialize',validate(lessonCheckoutSchema),respond(req=>paystackService.initializeLesson(req.teacher,req.validated.body)));
teacherRouter.post('/billing/paystack/verify',validate(paymentVerifySchema),respond(req=>paystackService.verifyLesson(req.teacher,req.validated.body.reference)));
teacherRouter.get('/billing/quote',validate(lessonQuoteSchema),respond(async req=>({...await billing.quote(req.teacher,req.validated.query.planId),paystack:{enabled:Boolean(paystackClient.mode),mode:paystackClient.mode},contact:await prisma.platformSettings.findUnique({where:{id:'platform'},select:{supportEmail:true,supportPhone:true}})})));
teacherRouter.post('/billing/purchases',validate(lessonPurchaseSchema),respond(req=>billing.request(req.teacher,req.validated.body),201));
teacherRouter.use('/lesson-plans',authenticateTeacher);
teacherRouter.get('/lesson-plans/options',respond(()=>lessons.options()));
teacherRouter.get('/lesson-plans',validate(listLessonSchema),respond(req=>lessons.list(req.teacher,req.validated.query)));
teacherRouter.post('/lesson-plans',validate(personalCreateSchema),respond(req=>lessons.create(req.teacher,req.validated.body),201));
teacherRouter.get('/lesson-plans/:id/booklet',validate(getLessonSchema),respond(req=>lessons.booklet(req.teacher,req.validated.params.id)));
teacherRouter.get('/lesson-plans/:id',validate(getLessonSchema),respond(req=>lessons.get(req.teacher,req.validated.params.id)));
teacherRouter.put('/lesson-plans/:id',validate(personalUpdateSchema),respond(req=>lessons.update(req.teacher,req.validated.params.id,req.validated.body)));
